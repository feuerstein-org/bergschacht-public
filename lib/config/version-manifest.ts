/**
 * Version manifest accessors backed by a local JSON cache file.
 *
 * Application repos write artifact metadata to SSM Parameter Store in the CICD
 * account.  Before CDK synth the pipeline synth step dumps all SSM parameters under /{ssmPrefix} into
 * {@link VERSION_MANIFEST_PATH}.
 *
 * SSM layout (source of truth, written by app repos):
 *   /{ssmPrefix}/{repoName}/lambdas/{artifactName} -> LambdaArtifact JSON
 *   /{ssmPrefix}/{repoName}/images/{artifactName} -> ContainerArtifact JSON
 *
 * Local cache layout (version-manifest.json):
 *   { "/{ssmPrefix}/repo/lambdas/name": { ... }, ... }
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import * as ecr from 'aws-cdk-lib/aws-ecr';
import * as ecs from 'aws-cdk-lib/aws-ecs';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import { Construct } from 'constructs';
import { ssmPrefix } from './constants';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/** Lambda artifact stored in S3. */
export interface LambdaArtifact {
  /** S3 bucket containing the Lambda artifact */
  bucket: string;
  /** S3 object key (path to zip file) */
  key: string;
  /** S3 object version ID */
  objectVersion: string;
  /** Semantic version of the artifact */
  version: string;
  /** Git commit SHA that produced this artifact (7-40 chars) */
  commitSha: string;
}

/** Container image stored in ECR. */
export interface ContainerArtifact {
  /** Full ECR repository URI */
  repository: string;
  /** Docker image tag */
  imageTag: string;
  /** Semantic version of the artifact */
  version: string;
  /** Git commit SHA that produced this image (7-40 chars) */
  commitSha: string;
}

// ---------------------------------------------------------------------------
// Manifest cache
// ---------------------------------------------------------------------------

/** SSM parameter prefix for all version manifest data */
export const SSM_PREFIX = `/${ssmPrefix}`;

/**
 * Absolute path to the local version manifest cache file.
 * Generated by `mise run refresh-manifest` (local) or the pipeline synth step (CI).
 */
export const VERSION_MANIFEST_PATH = path.resolve(__dirname, '..', '..', 'version-manifest.json');

/** Parsed manifest cache - loaded lazily on first access. */
let manifestCache: Record<string, string> | undefined;

/**
 * Load and cache the version manifest from disk.
 * @throws Error if the file does not exist (forgot to run refresh-manifest?)
 */
function loadManifest(): Record<string, string> {
  if (manifestCache) return manifestCache;

  if (!fs.existsSync(VERSION_MANIFEST_PATH)) {
    throw new Error(
      `Version manifest not found at ${VERSION_MANIFEST_PATH}.\n` +
        'Run "mise run refresh-manifest" to populate it from SSM, ' +
        'or ensure the pipeline synth step dumps SSM before cdk synth.'
    );
  }

  const raw: { Name: string; Value: string }[] = JSON.parse(
    fs.readFileSync(VERSION_MANIFEST_PATH, 'utf-8')
  );
  manifestCache = Object.fromEntries(raw.map((p) => [p.Name, p.Value]));
  return manifestCache;
}

/** Reset the in-memory cache (useful in tests). */
export function _resetManifestCache(): void {
  manifestCache = undefined;
}

/**
 * Inject manifest data directly (for tests - avoids filesystem mocking).
 * Accepts the same format as the JSON file (array of `{Name, Value}` entries).
 */
export function _loadManifestFromData(entries: { Name: string; Value: string }[]): void {
  manifestCache = Object.fromEntries(entries.map((p) => [p.Name, p.Value]));
}

/** Look up a single parameter value from the cached manifest. */
function lookup(parameterName: string): string {
  const manifest = loadManifest();
  const value = manifest[parameterName];
  if (value === undefined) {
    throw new Error(
      `Artifact parameter '${parameterName}' not found in ${VERSION_MANIFEST_PATH}.\n` +
        'Run "mise run refresh-manifest" to update the local cache.'
    );
  }
  return value;
}

/**
 * Get a named Lambda artifact from the local manifest cache.
 *
 * @example
 * const artifact = getLambdaArtifact('sample-python-repo', 'sample-etl-pipeline');
 * new lambda.Function(this, 'Fn', {
 *   code: lambda.Code.fromBucket(
 *     s3.Bucket.fromBucketName(this, 'Bucket', artifact.bucket),
 *     artifact.key,
 *     artifact.objectVersion,
 *   ),
 *   ...
 * });
 */
export function getLambdaArtifact(repoName: string, artifactName: string): LambdaArtifact {
  const json = lookup(`${SSM_PREFIX}/${repoName}/lambdas/${artifactName}`);
  return JSON.parse(json) as LambdaArtifact;
}

/**
 * Get a named container image artifact from the local manifest cache.
 *
 * @example
 * const artifact = getImageArtifact('sample-python-repo', 'sample-etl-pipeline');
 * const image = getContainerImage(this, 'SampleImage', artifact);
 */
export function getImageArtifact(repoName: string, artifactName: string): ContainerArtifact {
  const json = lookup(`${SSM_PREFIX}/${repoName}/images/${artifactName}`);
  return JSON.parse(json) as ContainerArtifact;
}

/**
 * Parse a ContainerArtifact's ECR repository URI into its component pieces.
 *
 * @throws Error if `artifact.repository` is not a recognizable ECR URI.
 */
function parseEcrRepository(
  scope: Construct,
  id: string,
  artifact: ContainerArtifact
): ecr.IRepository {
  const [host, ...pathParts] = artifact.repository.split('/');
  if (!host) {
    throw new Error(`Invalid repository with empty host: ${artifact.repository}`);
  }
  const name = pathParts.join('/');
  const hostMatch = /^(\d{12})\.dkr\.ecr\.([a-z0-9-]+)\.amazonaws\.com$/.exec(host);
  if (!hostMatch || !name) {
    throw new Error(`Unrecognized ECR repository URI: ${artifact.repository}`);
  }
  const region = hostMatch[2];
  const account = hostMatch[1];
  const repository = ecr.Repository.fromRepositoryAttributes(scope, id, {
    repositoryArn: `arn:aws:ecr:${region}:${account}:repository/${name}`,
    repositoryName: name,
  });
  return repository;
}

/**
 * Build an `ecs.ContainerImage` for a ContainerArtifact
 *
 * @throws Error if `artifact.repository` is not a recognizable ECR URI.
 */
export function getContainerImage(
  scope: Construct,
  id: string,
  artifact: ContainerArtifact
): ecs.ContainerImage {
  const repository = parseEcrRepository(scope, id, artifact);
  return ecs.ContainerImage.fromEcrRepository(repository, artifact.imageTag);
}

/**
 * Build `lambda.DockerImageCode` for a ContainerArtifact
 *
 * @throws Error if `artifact.repository` is not a recognizable ECR URI.
 */
export function getLambdaDockerImageCode(
  scope: Construct,
  id: string,
  artifact: ContainerArtifact
): lambda.DockerImageCode {
  const repository = parseEcrRepository(scope, id, artifact);
  return lambda.DockerImageCode.fromEcr(repository, { tagOrDigest: artifact.imageTag });
}
